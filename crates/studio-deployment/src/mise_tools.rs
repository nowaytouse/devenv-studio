use anyhow::{Context, Result, ensure};
use serde::{Deserialize, Serialize};
use std::{
    collections::{BTreeMap, BTreeSet},
    fs::{self, OpenOptions},
    io::{Read, Write},
    path::{Path, PathBuf},
    process,
    sync::{
        Arc,
        atomic::{AtomicBool, AtomicU64, Ordering},
    },
    time::{Duration, SystemTime, UNIX_EPOCH},
};

const MAX_TOOLS: usize = 512;
const MAX_REQUEST_BYTES: u64 = 1024 * 1024;
const MAX_LOCK_BYTES: u64 = 4 * 1024 * 1024;
const LOCK_PLATFORMS: &str = "macos-arm64,macos-x64,windows-x64";

pub const CORE_RUNTIMES: &[&str] = &[
    "bun", "deno", "dotnet", "go", "java", "node", "python", "ruby", "zig",
];

#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct RuntimeRequest {
    pub name: String,
    /// A concrete version or a mise version request such as latest, lts, beta or a prefix.
    pub version: String,
}

#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Request {
    pub schema_version: u8,
    pub runtimes: Vec<RuntimeRequest>,
}

#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
pub struct InstalledRuntime {
    pub name: String,
    pub version: String,
    pub scheduled_for_pruning: bool,
}

#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
pub struct RuntimeResult {
    pub name: String,
    pub requested_version: String,
    pub resolved_version: String,
    pub action: String,
}

#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
pub struct Report {
    pub requested: usize,
    pub verified: bool,
    pub cancelled: bool,
    pub runtimes: Vec<RuntimeResult>,
    pub detail: String,
    pub evidence: Option<PathBuf>,
    pub manifest: Option<PathBuf>,
    pub lockfile: Option<PathBuf>,
}

pub fn supports_runtime(name: &str) -> bool {
    CORE_RUNTIMES.contains(&name)
}

pub fn validate(request: &Request) -> Result<()> {
    ensure!(
        request.schema_version == 1,
        "Unsupported mise request schema"
    );
    ensure!(
        !request.runtimes.is_empty() && request.runtimes.len() <= MAX_TOOLS,
        "Select 1 to 512 mise runtimes"
    );
    let mut identities = BTreeSet::new();
    for runtime in &request.runtimes {
        ensure!(
            supports_runtime(&runtime.name),
            "Only reviewed mise core runtimes are supported"
        );
        validate_version_request(&runtime.version)?;
        ensure!(
            identities.insert((runtime.name.as_str(), runtime.version.as_str())),
            "Duplicate mise runtime request"
        );
    }
    Ok(())
}

fn validate_version_request(version: &str) -> Result<()> {
    let channel = matches!(version, "latest" | "stable" | "lts" | "beta" | "nightly");
    ensure!(
        channel
            || (!version.is_empty()
                && version.len() <= 128
                && version
                    .as_bytes()
                    .first()
                    .is_some_and(u8::is_ascii_alphanumeric)
                && version
                    .as_bytes()
                    .last()
                    .is_some_and(u8::is_ascii_alphanumeric)
                && version.bytes().any(|byte| byte.is_ascii_digit())
                && version
                    .bytes()
                    .all(|byte| byte.is_ascii_alphanumeric() || b".+_-".contains(&byte))),
        "Use a version, prefix or supported mise channel without paths or backend syntax"
    );
    Ok(())
}

fn version_is_concrete(version: &str) -> bool {
    version.matches('.').count() >= 2
}

pub fn mise_toml(request: &Request) -> Result<String> {
    validate(request)?;
    render_mise_toml(&request.runtimes)
}

fn render_mise_toml(runtimes: &[RuntimeRequest]) -> Result<String> {
    let mut grouped = BTreeMap::<&str, BTreeSet<&str>>::new();
    for runtime in runtimes {
        ensure!(
            supports_runtime(&runtime.name),
            "Only reviewed mise core runtimes are supported"
        );
        validate_version_request(&runtime.version)?;
        grouped
            .entry(&runtime.name)
            .or_default()
            .insert(&runtime.version);
    }
    let mut text =
        String::from("# Generated by DevEnv Studio. Review versions before use.\n[tools]\n");
    for (name, versions) in grouped {
        let versions = versions
            .into_iter()
            .map(|version| format!("\"{version}\""))
            .collect::<Vec<_>>()
            .join(", ");
        text.push_str(&format!("\"core:{name}\" = [{versions}]\n"));
    }
    Ok(text)
}

pub fn save(request: &Request, path: &Path) -> Result<()> {
    validate(request)?;
    studio_core::export_document(request, path)
}

pub fn load(path: &Path) -> Result<Request> {
    let metadata = fs::symlink_metadata(path).context("Inspect mise request")?;
    ensure!(
        metadata.file_type().is_file(),
        "Mise request must be a regular file"
    );
    ensure!(
        metadata.len() <= MAX_REQUEST_BYTES,
        "Mise request exceeds the 1 MiB limit"
    );
    let file = OpenOptions::new()
        .read(true)
        .open(path)
        .context("Open mise request")?;
    let mut bytes = Vec::with_capacity(metadata.len() as usize);
    file.take(MAX_REQUEST_BYTES + 1)
        .read_to_end(&mut bytes)
        .context("Read mise request")?;
    ensure!(
        bytes.len() as u64 <= MAX_REQUEST_BYTES,
        "Mise request exceeds the 1 MiB limit"
    );
    let request: Request = serde_json::from_slice(&bytes).context("Parse mise request")?;
    validate(&request)?;
    Ok(request)
}

#[derive(Deserialize)]
struct ListEntry {
    version: String,
    installed: Option<bool>,
    #[serde(default)]
    scheduled_for_pruning: bool,
}

pub fn parse_inventory(output: &str) -> Result<Vec<InstalledRuntime>> {
    let listing: BTreeMap<String, Vec<ListEntry>> =
        serde_json::from_str(output).context("Parse mise core inventory JSON")?;
    let mut found = BTreeMap::new();
    for (raw_name, entries) in listing {
        let name = match raw_name.as_str() {
            "nodejs" => "node".to_owned(),
            "golang" => "go".to_owned(),
            _ => raw_name,
        };
        if !supports_runtime(&name) {
            continue;
        }
        ensure!(
            !name.is_empty()
                && name.len() <= 64
                && name.bytes().all(|byte| {
                    byte.is_ascii_lowercase() || byte.is_ascii_digit() || b"_-".contains(&byte)
                }),
            "Mise returned an invalid core runtime identity"
        );
        for entry in entries {
            ensure!(
                entry.installed.is_some(),
                "This mise version returned an unsupported inventory record"
            );
            if !entry.installed.unwrap_or(false) {
                continue;
            }
            validate_version_request(&entry.version)
                .context("Mise returned an invalid installed version")?;
            found.insert(
                (name.clone(), entry.version.clone()),
                InstalledRuntime {
                    name: name.clone(),
                    version: entry.version,
                    scheduled_for_pruning: entry.scheduled_for_pruning,
                },
            );
        }
    }
    Ok(found.into_values().collect())
}

pub fn mise_program() -> Result<PathBuf> {
    let home_variable = if cfg!(windows) { "USERPROFILE" } else { "HOME" };
    let home = PathBuf::from(
        std::env::var_os(home_variable).context("User home directory is unavailable")?,
    );
    ensure!(
        home.is_absolute() && home.is_dir(),
        "A standard absolute user home is required to locate mise"
    );
    let executable = if cfg!(windows) { "mise.exe" } else { "mise" };
    let mut candidates = vec![home.join(".local/bin").join(executable)];
    #[cfg(target_os = "macos")]
    {
        candidates.push(PathBuf::from("/opt/homebrew/bin/mise"));
        candidates.push(PathBuf::from("/usr/local/bin/mise"));
    }
    #[cfg(windows)]
    {
        if let Some(local_app_data) = std::env::var_os("LOCALAPPDATA") {
            candidates.push(PathBuf::from(local_app_data).join("Microsoft/WinGet/Links/mise.exe"));
        }
        candidates.push(home.join("scoop/shims/mise.exe"));
    }
    if let Some(path) = std::env::var_os("PATH") {
        candidates.extend(std::env::split_paths(&path).map(|directory| directory.join(executable)));
    }
    let program = candidates
        .into_iter()
        .find(|path| path.is_absolute() && path.is_file())
        .context("Install the official mise executable in its standard location or PATH first")?;
    ensure!(
        fs::metadata(&program).is_ok_and(|metadata| metadata.is_file()),
        "The mise executable is not a regular file"
    );
    Ok(program)
}

pub fn capture(cancel: Arc<AtomicBool>) -> Result<Vec<InstalledRuntime>> {
    #[cfg(any(windows, target_os = "macos"))]
    {
        let program = mise_program()?;
        let workspace = Workspace::create()?;
        let result = step(
            &mut InventoryRunner {
                timeout: Duration::from_secs(60),
                workspace: workspace.0.clone(),
            },
            &program,
            &list_args(),
            &cancel,
        );
        let cleanup = workspace.cleanup();
        let text = match (result, cleanup) {
            (Ok(text), Ok(())) => text,
            (Err(error), Ok(())) => return Err(error),
            (Ok(_), Err(error)) => return Err(error.context("Clean up mise inventory workspace")),
            (Err(error), Err(cleanup)) => {
                return Err(error.context(format!(
                    "Mise inventory workspace cleanup also failed: {cleanup}"
                )));
            }
        };
        parse_inventory(&text)
    }
    #[cfg(not(any(windows, target_os = "macos")))]
    {
        let _ = cancel;
        anyhow::bail!("Native mise runtime inventory requires macOS or Windows")
    }
}

