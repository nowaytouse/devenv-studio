    #[test]
    fn bundle_persists_exact_intent_and_sanitized_success_failure_or_cancel_outcome() -> Result<()>
    {
        let directory = TestDirectory::new()?;
        for (status, outputs, calls, succeeds) in [
            ("verified", vec![output(0), output(0)], 2, true),
            ("failed", vec![output(0), output(1)], 2, false),
            (
                "cancelled",
                vec![Output {
                    cancelled: true,
                    ..output(0)
                }],
                1,
                true,
            ),
            ("failed", Vec::new(), 1, false),
        ] {
            let history = create_history(&directory.0)?;
            let mut outputs: std::collections::VecDeque<_> = outputs.into();
            for output in &mut outputs {
                output.stdout = "private output is never recorded".into();
                output.stderr = "private diagnostics are never recorded".into();
            }
            let mut runner = Fake {
                calls: vec![],
                outputs,
            };
            let requested = entries();
            let result = run_recorded_bundle(
                &mut runner,
                directory.0.join("brew"),
                &directory.0.join("Brewfile"),
                &requested,
                &Arc::new(AtomicBool::new(false)),
                &mut |name, value| studio_core::export_document(value, &history.join(name)),
            );
            assert_eq!(result.is_ok(), succeeds);
            assert_eq!(runner.calls.len(), calls);
            let request = read_record(&history.join("request.json"))?;
            assert_eq!(request["event"], "started");
            assert_eq!(request["requested"], serde_json::to_value(&requested)?);
            assert_eq!(request["versions_pinned"], false);
            let terminal = read_record(&history.join("result.json"))?;
            assert_eq!(terminal["event"], "finished");
            assert_eq!(terminal["status"], status);
            assert_eq!(terminal["verified"], status == "verified");
            assert_eq!(terminal["cancelled"], status == "cancelled");
            for name in ["request.json", "result.json"] {
                assert!(!std::fs::read_to_string(history.join(name))?.contains("private"));
            }
            #[cfg(unix)]
            {
                use std::os::unix::fs::PermissionsExt;
                assert_eq!(
                    std::fs::metadata(&history)?.permissions().mode() & 0o777,
                    0o700
                );
            }
        }
        Ok(())
    }

