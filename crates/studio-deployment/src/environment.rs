    #[test]
    fn bundle_history_refuses_non_directory_or_linked_locations() -> Result<()> {
        let directory = TestDirectory::new()?;
        let existing = directory.0.join("existing");
        std::fs::write(&existing, b"Existing external file")?;
        assert!(create_history(&existing).is_err());
        assert_eq!(std::fs::read(&existing)?, b"Existing external file");
        #[cfg(unix)]
        {
            let linked = directory.0.join("environment-history");
            let external = directory.0.join("external");
            std::fs::create_dir(&external)?;
            std::os::unix::fs::symlink(&external, &linked)?;
            assert!(create_history(&directory.0).is_err());
            assert_eq!(std::fs::read_dir(external)?.count(), 0);
            assert!(std::fs::symlink_metadata(linked)?.file_type().is_symlink());
        }
        Ok(())
    }

    #[test]
    fn bundle_success_requires_presence_check_and_cancellation_starts_nothing() {
        let mut runner = Fake {
            calls: vec![],
            outputs: [output(0), output(1)].into(),
        };
        let cancel = Arc::new(AtomicBool::new(false));
        let program = std::env::temp_dir().join("synthetic-brew");
        let manifest = std::env::temp_dir().join("synthetic-Brewfile");
        let path = manifest.as_path();
        assert!(run_bundle(&mut runner, program.clone(), path, 2, &cancel).is_err());
        assert_eq!(runner.calls.len(), 2);
        assert_eq!(
            runner.calls[0].args,
            vec![
                "bundle".to_string(),
                "install".into(),
                "--no-upgrade".into(),
                format!("--file={}", path.display())
            ]
        );
        assert_eq!(runner.calls[1].args[1], "check");
        cancel.store(true, Ordering::Release);
        runner.calls.clear();
        assert!(run_bundle(&mut runner, program.clone(), path, 2, &cancel).is_err());
        assert!(runner.calls.is_empty());
        cancel.store(false, Ordering::Release);
        runner.outputs = [output(0), output(0)].into();
        assert!(
            run_bundle(&mut runner, program, path, 2, &cancel)
                .unwrap()
                .verified
        );
    }
