#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct BrewEntry {
    pub kind: String,
    pub name: String,
}
impl BrewEntry {
    pub fn id(&self) -> String {
        format!("{}:{}", self.kind, self.name)
    }
}

pub fn brew_candidates(snapshot: Option<&Snapshot>) -> Result<Vec<BrewEntry>> {
    let mut entries = BTreeSet::new();
    for (kind, name) in [
        ("brew_formula", "git"),
        ("brew_formula", "rustup"),
        ("brew_formula", "uv"),
        ("brew_formula", "node"),
        ("brew_formula", "python@3.14"),
        ("brew_formula", "cmake"),
        ("brew_cask", "visual-studio-code"),
    ] {
        entries.insert(BrewEntry {
            kind: kind.into(),
            name: name.into(),
        });
    }
    if let Some(snapshot) = snapshot {
        crate::backup::validate(snapshot)?;
        if snapshot.platform == "macos" {
            for provider in &snapshot.providers {
                if provider.status == "complete"
                    && matches!(provider.kind.as_str(), "brew_formula" | "brew_cask")
                {
                    for package in &provider.packages {
                        entries.insert(BrewEntry {
                            kind: provider.kind.clone(),
                            name: package.name.clone(),
                        });
                    }
                }
            }
        }
    }
    Ok(entries.into_iter().collect())
}
pub fn selected_brew(
    snapshot: Option<&Snapshot>,
    selected: &BTreeSet<String>,
) -> Result<Vec<BrewEntry>> {
    let candidates = brew_candidates(snapshot)?;
    let entries: Vec<_> = candidates
        .into_iter()
        .filter(|e| selected.contains(&e.id()))
        .collect();
    ensure!(
        entries.len() == selected.len(),
        "A selected Mac package is no longer in the reviewed inventory"
    );
    validate_brew(&entries)?;
    Ok(entries)
}
fn validate_brew(entries: &[BrewEntry]) -> Result<()> {
    ensure!(
        !entries.is_empty() && entries.len() <= crate::MAX_SESSION_TASKS,
        "Select 1 to 128 Mac packages"
    );
    let mut ids = BTreeSet::new();
    for entry in entries {
        ensure!(
            matches!(entry.kind.as_str(), "brew_formula" | "brew_cask"),
            "Unsupported Bundle entry"
        );
        let n = entry.name.as_bytes();
        ensure!(
            !n.is_empty()
                && n.len() <= 128
                && n[0].is_ascii_alphanumeric()
                && n.iter()
                    .all(|b| b.is_ascii_alphanumeric() || b"-_.@+".contains(b)),
            "Invalid Homebrew identity"
        );
        ensure!(ids.insert(entry.id()), "Duplicate Bundle entry");
    }
    Ok(())
}
pub fn brewfile(entries: &[BrewEntry]) -> Result<String> {
    validate_brew(entries)?;
    let mut text = String::from(
        "# Generated by LTSC Studio. Reviewed package identities; versions are not pinned.\n",
    );
    for entry in entries {
        text.push_str(if entry.kind == "brew_cask" {
            "cask \""
        } else {
            "brew \""
        });
        text.push_str(&entry.name);
        text.push_str("\"\n");
    }
    Ok(text)
}
pub fn export_brewfile(entries: &[BrewEntry], path: &Path) -> Result<()> {
    studio_core::export_bytes(brewfile(entries)?.as_bytes(), path)
}

/// Exports only package identities from a validated Windows plan, never arbitrary installer switches.
pub fn export_winget(plan: &crate::DeploymentPlan, path: &Path) -> Result<()> {
    crate::validate_plan(plan)?;
    let packages: Vec<_> = plan
        .tasks
        .iter()
        .filter(|t| t.kind == "package")
        .map(|t| serde_json::json!({"PackageIdentifier":t.package_id}))
        .collect();
    ensure!(
        !packages.is_empty(),
        "The Windows plan contains no WinGet packages"
    );
    let document = serde_json::json!({
        "$schema":"https://aka.ms/winget-packages.schema.2.0.json",
        "Sources":[{"SourceDetails":{"Argument":"https://cdn.winget.microsoft.com/cache",
            "Identifier":"Microsoft.Winget.Source_8wekyb3d8bbwe",
            "Name":"winget","Type":"Microsoft.PreIndexed.Package"},
            "Packages":packages}]
    });
    studio_core::export_document(&document, path)
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct BundleReport {
    pub requested: usize,
    pub verified: bool,
    pub cancelled: bool,
    pub detail: String,
}
pub fn configure_brew(entries: Vec<BrewEntry>, cancel: Arc<AtomicBool>) -> Result<BundleReport> {
    validate_brew(&entries)?;
    #[cfg(target_os = "macos")]
    {
        let program = crate::backup::homebrew_program()
            .context("Homebrew and its local runtime are required")?;
        let manifest = PrivateBundle::create(&brewfile(&entries)?)?;
        let result: Result<BundleReport> = (|| {
            let history = create_history(&studio_platform::data_directory()?)?;
            let before = crate::backup::collect(Arc::clone(&cancel))?;
            save_baseline(&before, &history.join("before.json"))?;
            let mut report = run_recorded_bundle(
                &mut Native,
                program,
                &manifest.path,
                &entries,
                &cancel,
                &mut |name, value| {
                    studio_core::export_document(value, &history.join(name))
                },
            )
            .with_context(|| format!(
                "Mac configuration evidence: {}. Partial changes may exist; no automatic rollback is available.",
                history.display()
            ))?;
            report
                .detail
                .push_str(&format!(" Execution evidence: {}", history.display()));
            Ok(report)
        })();
        let cleanup = manifest.finish();
        let report = result?;
        cleanup?;
        Ok(report)
    }
    #[cfg(not(target_os = "macos"))]
    {
        let _ = cancel;
        anyhow::bail!("Native Homebrew configuration requires macOS");
    }
}
#[cfg(any(target_os = "macos", test))]
fn save_baseline(snapshot: &Snapshot, path: &Path) -> Result<()> {
    crate::backup::validate(snapshot)?;
    ensure!(
        snapshot.platform == "macos",
        "Mac configuration requires a native Mac baseline"
    );
    for kind in ["brew_formula", "brew_cask"] {
        ensure!(
            snapshot
                .providers
                .iter()
                .any(|p| p.kind == kind && p.status == "complete"),
            "Homebrew baseline capture was incomplete; no configuration was started"
        );
    }
    studio_core::export_document(snapshot, path)
        .context("Persist the native inventory before configuration")
}

#[cfg(any(target_os = "macos", test))]
fn create_history(data: &Path) -> Result<std::path::PathBuf> {
    use std::{
        fs,
        time::{SystemTime, UNIX_EPOCH},
    };
    ensure!(
        data.is_absolute(),
        "Application data directory must be absolute"
    );
    fs::create_dir_all(data).context("Create application data directory before configuration")?;
    ensure!(
        fs::symlink_metadata(data)?.is_dir(),
        "Application data must be a real directory"
    );
    let root = data.join("environment-history");
    #[cfg(unix)]
    let mut builder = fs::DirBuilder::new();
    #[cfg(not(unix))]
    let builder = fs::DirBuilder::new();
    #[cfg(unix)]
    {
        use std::os::unix::fs::DirBuilderExt;
        builder.mode(0o700);
    }
    match builder.create(&root) {
        Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => {}
        result => result.context("Create Mac configuration history directory")?,
    }
    ensure!(
        fs::symlink_metadata(&root)?.is_dir(),
        "Mac configuration history must be a real directory"
    );
    #[cfg(unix)]
    fs::File::open(data)?
        .sync_all()
        .context("Flush Mac configuration history location")?;
    static SEQUENCE: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);
    let now = SystemTime::now().duration_since(UNIX_EPOCH)?.as_nanos();
    for _ in 0..32 {
        let sequence = SEQUENCE.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
        let path = root.join(format!("{now}-{}-{sequence}", std::process::id()));
        match builder.create(&path) {
            Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => continue,
            result => result.context("Create private Mac configuration run directory")?,
        }
        #[cfg(unix)]
        fs::File::open(&root)?
            .sync_all()
            .context("Flush configuration history directory")?;
        return Ok(path);
    }
    anyhow::bail!("No unused Mac configuration history directory")
}

#[cfg(any(target_os = "macos", test))]
fn run_recorded_bundle(
    runner: &mut impl crate::process::Runner,
    program: std::path::PathBuf,
    manifest: &Path,
    entries: &[BrewEntry],
    cancel: &Arc<AtomicBool>,
    persist: &mut impl FnMut(&str, &serde_json::Value) -> Result<()>,
) -> Result<BundleReport> {
    validate_brew(entries)?;
    persist("request.json", &serde_json::json!({
        "schema_version": 1,
        "event": "started",
        "platform": "macos",
        "provider": "homebrew_bundle",
        "requested": entries,
        "versions_pinned": false,
        "completion": "Unknown until result.json is present. A started record does not prove installation or rollback.",
    })).context("Persist and flush the Mac configuration request before any command")?;
    let result = run_bundle(runner, program, manifest, entries.len(), cancel);
    let verified = result.as_ref().is_ok_and(|report| report.verified);
    let cancelled = result.as_ref().is_ok_and(|report| report.cancelled)
        || (!verified && cancel.load(std::sync::atomic::Ordering::Acquire));
    persist("result.json", &serde_json::json!({
        "schema_version": 1,
        "event": "finished",
        "status": if verified { "verified" } else if cancelled { "cancelled" } else { "failed" },
        "requested": entries.len(),
        "verified": verified,
        "cancelled": cancelled,
        "detail": if verified {
            "Bundle install and independent presence check completed. Versions and tool execution were not verified; no automatic rollback is available."
        } else {
            "Configuration did not complete with verified presence. Partial changes may exist and descendant installers may still be running; inspect before retrying."
        },
    })).context("Terminal Mac configuration evidence could not be persisted; the started record remains unresolved and partial changes may exist")?;
    result
}

#[cfg(any(target_os = "macos", test))]
fn run_bundle(
    runner: &mut impl crate::process::Runner,
    program: std::path::PathBuf,
    manifest: &Path,
    requested: usize,
    cancel: &Arc<AtomicBool>,
) -> Result<BundleReport> {
    use crate::process::Invocation;
    use std::sync::atomic::Ordering;
    ensure!(
        program.is_absolute() && manifest.is_absolute(),
        "Bundle paths must be absolute"
    );
    ensure!(
        !cancel.load(Ordering::Acquire),
        "Configuration cancelled before starting"
    );
    for step in ["install", "check"] {
        let output = runner.run(
            &Invocation {
                program: program.clone(),
                args: vec![
                    "bundle".into(),
                    step.into(),
                    "--no-upgrade".into(),
                    format!("--file={}", manifest.display()),
                ],
                vscode_node: false,
                npm_node: false,
            },
            cancel,
        )?;
        if output.cancelled || cancel.load(Ordering::Acquire) {
            return Ok(BundleReport { requested, verified:false, cancelled:true,
                detail:"Configuration cancelled. Packages or dependencies may have changed and descendant installers may still be running; inspect the environment before retrying.".into() });
        }
        ensure!(
            !output.timed_out,
            "Homebrew Bundle timed out; installed state is not verified"
        );
        ensure!(
            output.code == 0,
            "Homebrew Bundle {step} failed; installed state is not verified"
        );
    }
    Ok(BundleReport { requested, verified:true, cancelled:false,
        detail:"Homebrew Bundle install and independent presence check completed. Versions, tool execution and project behavior are not verified. Dependencies may have changed; no automatic rollback is available.".into() })
}
#[cfg(target_os = "macos")]
struct Native;
#[cfg(target_os = "macos")]
impl crate::process::Runner for Native {
    fn run(
        &mut self,
        invocation: &crate::process::Invocation,
        cancel: &Arc<AtomicBool>,
    ) -> Result<crate::process::Output> {
        crate::process::run_bounded(invocation, cancel, std::time::Duration::from_secs(90 * 60))
    }
}
#[cfg(target_os = "macos")]
struct PrivateBundle {
    path: std::path::PathBuf,
}
#[cfg(target_os = "macos")]
impl PrivateBundle {
    fn create(text: &str) -> Result<Self> {
        use std::{
            fs::{DirBuilder, OpenOptions},
            io::Write,
            os::unix::fs::{DirBuilderExt, OpenOptionsExt},
        };
        static SEQUENCE: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);
        for _ in 0..32 {
            let sequence = SEQUENCE.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
            let root =
                std::env::temp_dir().join(format!("ltsc-bundle-{}-{sequence}", std::process::id()));
            match DirBuilder::new().mode(0o700).create(&root) {
                Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => continue,
                result => result.context("Create private Bundle staging directory")?,
            }
            let value = Self {
                path: root.join("Brewfile"),
            };
            let mut file = OpenOptions::new()
                .write(true)
                .create_new(true)
                .mode(0o600)
                .open(&value.path)?;
            file.write_all(text.as_bytes())?;
            file.sync_all()?;
            return Ok(value);
        }
        anyhow::bail!("No unused private Bundle staging directory")
    }
    fn finish(self) -> Result<()> {
        std::fs::remove_file(&self.path).context("Remove generated Bundle staging file")?;
        std::fs::remove_dir(
            self.path
                .parent()
                .context("Bundle staging directory missing")?,
        )
        .context("Remove Bundle staging directory")
    }
}

