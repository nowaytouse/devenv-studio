    struct Fake {
        calls: Vec<Invocation>,
        outputs: std::collections::VecDeque<Output>,
    }
    impl Runner for Fake {
        fn run(&mut self, i: &Invocation, _: &Arc<AtomicBool>) -> Result<Output> {
            self.calls.push(i.clone());
            self.outputs.pop_front().context("Missing fake output")
        }
    }
    fn output(code: u32) -> Output {
        Output {
            code,
            stdout: String::new(),
            stderr: String::new(),
            cancelled: false,
            timed_out: false,
        }
    }
    struct TestDirectory(std::path::PathBuf);
